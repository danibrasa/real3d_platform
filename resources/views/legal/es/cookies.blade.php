<h2>1. Qué son</h2>
<p>Una cookie es un pequeño fichero que el navegador guarda cuando visita una web, y que permite recordar cosas entre una página y otra: que ha iniciado sesión, qué idioma prefiere. {{ $marca }} usa pocas, y las analíticas solo si usted las acepta.</p>

<h2>2. Cookies necesarias</h2>
<p>Se instalan siempre, porque sin ellas el servicio no funciona. No requieren consentimiento.</p>
<ul>
    <li><strong>Sesión</strong> (<code>real3d_session</code> o similar): mantiene su sesión iniciada mientras navega. Caduca al cerrar el navegador o a las dos horas de inactividad.</li>
    <li><strong>Protección de formularios</strong> (<code>XSRF-TOKEN</code>): evita que otra web envíe formularios en su nombre.</li>
    <li><strong>Idioma y moneda</strong>: recuerdan su preferencia cuando la cambia.</li>
    <li><strong>Recordarme</strong>: solo si marca esa casilla al iniciar sesión, para no tener que hacerlo cada vez.</li>
</ul>
<p>El visor guarda además en el almacenamiento local del navegador un identificador de sesión anónimo y, si usa el asistente, la conversación en curso, para que no se pierda al cambiar de página. No salen de su navegador salvo para el uso descrito en la política de privacidad.</p>

<h2>3. Cookies analíticas</h2>
<p>Algunos proyectos usan Google Analytics para que la promotora sepa cuántas personas visitan su visor y qué miran. Esas cookies (<code>_ga</code>, <code>_ga_*</code>) solo se instalan si usted lo acepta en el aviso que aparece al abrir el visor. Si no acepta, el visor funciona igual y no se instalan.</p>

<h2>4. Cómo cambiar de opinión</h2>
<p>Puede retirar el consentimiento a las cookies analíticas desde el propio aviso, que vuelve a aparecer si borra los datos del sitio en su navegador, o borrando las cookies desde la configuración del navegador. También puede configurar el navegador para rechazar todas las cookies, aunque entonces no podrá iniciar sesión.</p>

